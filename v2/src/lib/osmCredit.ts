/**
 * The credit for OpenStreetMap data: the coast directions (derived from
 * VersaTiles' OSM vector tiles) and the map's raster tiles. The OSMF
 * Attribution Guidelines ask the credit to make clear that the data is
 * available under the Open Database License, normally by linking
 * "OpenStreetMap" to its copyright page; ODbL §4.3 asks the same of a
 * publicly used Produced Work (review C1).
 *
 * The translated credits (strings.ts: attribution, coast_osm,
 * coast_osm_list) say "(ODbL)" and hold an {osm} placeholder where
 * OsmCredit.vue puts the link, as template markup: no translated string is
 * ever rendered as HTML.
 */
export const OSM_COPYRIGHT_URL = 'https://www.openstreetmap.org/copyright'

/** Leaflet's credit for the OSM raster tiles. Leaflet renders it as HTML, so it is a constant here, never a translated string. */
export const OSM_TILE_ATTRIBUTION = `&copy; <a href="${OSM_COPYRIGHT_URL}" target="_blank" rel="noopener">OpenStreetMap</a> contributors`

export const ODBL_URL = 'https://opendatacommons.org/licenses/odbl/1-0/'
const DBCL_URL = 'https://opendatacommons.org/licenses/dbcl/1-0/'

/**
 * The header of src/lib/spotCoast.gen.ts, as coast-precompute.check.ts
 * writes it. The table is a database derived from OSM data, so it is offered
 * under the ODbL with the licence's own notice (review C5). It used to call
 * itself "an insubstantial extract", which the OSMF guideline does not back
 * for a systematic run over every coastal catalogue spot. The notice is a
 * legal comment, which the minifier keeps: the app precaches and serves the
 * table as its own chunk, and the licence travels with it (ODbL §4.2(b)).
 */
export function spotCoastHeader(o: { date: string; algo: number; count: number }): string[] {
  return [
    '// GENERATED by scripts/model-check/coast-precompute.check.ts (PRECOMPUTE=1) — do not edit.',
    `/*! SPOT_COAST: the coast of ${o.count} official spots (a facing, a 16-bin fetch profile and an exposure each),`,
    ` * derived from map data © OpenStreetMap contributors (${OSM_COPYRIGHT_URL}) via VersaTiles,`,
    ` * fetched ${o.date}, algorithm v${o.algo} (src/lib/coastGeometry.ts).`,
    ` * SPOT_COAST is made available under the Open Database License (ODbL) 1.0: ${ODBL_URL}`,
    ` * Any rights in its individual contents are licensed under the Database Contents License: ${DBCL_URL}`,
    ' */',
  ]
}

/** A translated credit, split around its {osm} placeholder: the link goes between the two. */
export function osmCreditParts(text: string): { before: string; after: string } {
  const i = text.indexOf('{osm}')
  return i < 0 ? { before: text, after: '' } : { before: text.slice(0, i), after: text.slice(i + '{osm}'.length) }
}
